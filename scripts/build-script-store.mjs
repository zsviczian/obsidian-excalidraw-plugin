import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const log = (...args) => console.log(...args);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const scriptsDir = path.join(root, "ea-scripts");
const catalogPath = path.join(scriptsDir, "script-store.json");
const legacyIndexPath = path.join(scriptsDir, "index-new.md");
const directoryInfoPath = path.join(scriptsDir, "directory-info.json");
const checkOnly = process.argv.includes("--check");
const FEATURED_CATEGORY = "Editors Picks";

const catalog = JSON.parse(fs.readFileSync(catalogPath, "utf8"));

const fail = (message) => {
  throw new Error(`[script-store] ${message}`);
};

const escapeHtml = (value) =>
  String(value ?? "")
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#039;");

const validateCatalog = () => {
  if (catalog.version !== 1) {
    fail(`Unsupported catalog version: ${catalog.version}`);
  }
  if (!Array.isArray(catalog.categories) || !Array.isArray(catalog.scripts)) {
    fail("Catalog must contain categories[] and scripts[].");
  }

  const categoryNames = new Set();
  for (const category of catalog.categories) {
    if (!category?.name || categoryNames.has(category.name)) {
      fail(`Invalid or duplicate category: ${category?.name ?? "<missing>"}`);
    }
    categoryNames.add(category.name);
  }

  const scriptNames = new Set();
  const scriptFiles = new Set();
  for (const script of catalog.scripts) {
    if (!script?.name || !script?.file || !script?.installUrl) {
      fail(`Script entry is missing name, file, or installUrl: ${JSON.stringify(script)}`);
    }
    if (scriptNames.has(script.name)) {
      fail(`Duplicate script name: ${script.name}`);
    }
    if (scriptFiles.has(script.file)) {
      fail(`Duplicate script file: ${script.file}`);
    }
    scriptNames.add(script.name);
    scriptFiles.add(script.file);

    const filePath = path.join(scriptsDir, script.file);
    if (!fs.existsSync(filePath) || !fs.statSync(filePath).isFile()) {
      fail(`Missing script file: ea-scripts/${script.file}`);
    }
    for (const category of script.categories ?? []) {
      if (!categoryNames.has(category)) {
        fail(`Unknown category "${category}" on ${script.name}`);
      }
    }
    if (
      script.featuredRank !== undefined &&
      !script.categories?.includes(FEATURED_CATEGORY)
    ) {
      fail(`${script.name} has featuredRank but is not in ${FEATURED_CATEGORY}.`);
    }
  }
};

const categoryScripts = (categoryName) =>
  catalog.scripts
    .filter((script) => script.categories?.includes(categoryName))
    .sort((a, b) => {
      if (categoryName === FEATURED_CATEGORY) {
        return (
          (a.featuredRank ?? Number.MAX_SAFE_INTEGER) -
            (b.featuredRank ?? Number.MAX_SAFE_INTEGER) ||
          a.name.localeCompare(b.name)
        );
      }
      return a.name.localeCompare(b.name);
    });

const generateLegacyIndex = () => {
  const current = fs.readFileSync(legacyIndexPath, "utf8");
  const newline = current.includes("\r\n") ? "\r\n" : "\n";
  const marker = "# List of available scripts";
  const generatedMarker =
    "<!-- The catalog and install sections below are generated by npm run script-store:build. -->";
  const markerIndex = current.indexOf(marker);
  if (markerIndex < 0) {
    fail(`Could not find "${marker}" in ea-scripts/index-new.md`);
  }
  const generatedMarkerIndex = current.indexOf(generatedMarker);
  const introEnd =
    generatedMarkerIndex >= 0 && generatedMarkerIndex < markerIndex
      ? generatedMarkerIndex
      : markerIndex;
  const intro = current.slice(0, introEnd).trimEnd();
  const lines = [intro, "", generatedMarker, marker, ""];

  for (const category of catalog.categories) {
    lines.push(`## ${category.name}`);
    if (category.description?.trim()) {
      lines.push(category.description.trim(), "");
    }
    lines.push("|    |     |", "|----|-----|");
    for (const script of categoryScripts(category.name)) {
      lines.push(
        `|<div><img src="${script.iconUrl}"/></div>|[[#${script.name}]]|`,
      );
    }
    lines.push("");
  }

  lines.push("---", "", "# Description and Installation", "");
  for (const script of [...catalog.scripts].sort((a, b) =>
    a.name.localeCompare(b.name),
  )) {
    lines.push(
      `## ${script.name}`,
      "```excalidraw-script-install",
      script.installUrl,
      "```",
      `<table><tr valign='top'><td class="label">Author</td><td class="data"><a href='${escapeHtml(script.authorUrl)}'>${escapeHtml(script.author)}</a></td></tr><tr valign='top'><td class="label">Source</td><td class="data"><a href='${escapeHtml(script.sourceUrl)}'>File on GitHub</a></td></tr><tr valign='top'><td class="label">Description</td><td class="data">${script.descriptionHtml.replace(/\r?\n/g, newline)}</td></tr></table>`,
      "",
    );
  }
  return `${lines.join(newline).trimEnd()}${newline}`;
};

const getGitMtime = (relativePath, existingMtime) => {
  try {
    const status = execFileSync(
      "git",
      ["status", "--porcelain", "--", relativePath],
      { cwd: root, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] },
    ).trim();
    if (status) {
      return fs.statSync(path.join(root, relativePath)).mtimeMs;
    }
    const seconds = execFileSync(
      "git",
      ["log", "-1", "--format=%ct", "--", relativePath],
      { cwd: root, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] },
    ).trim();
    if (seconds) {
      return Number(seconds) * 1000;
    }
  } catch {
    // Exported repository ZIPs do not contain .git. Preserve the existing
    // compatibility timestamp there; new files use their filesystem mtime.
  }
  return existingMtime ?? fs.statSync(path.join(root, relativePath)).mtimeMs;
};

const generateDirectoryInfo = () => {
  const existing = fs.existsSync(directoryInfoPath)
    ? JSON.parse(fs.readFileSync(directoryInfoPath, "utf8"))
    : [];
  const existingByName = new Map(existing.map((entry) => [entry.fname, entry.mtime]));
  const localFiles = fs
    .readdirSync(scriptsDir, { withFileTypes: true })
    .filter((entry) => entry.isFile())
    .map((entry) => entry.name);

  // Repository export ZIPs intentionally omit media such as script SVG icons.
  // Preserve their existing legacy metadata when .git is unavailable so a
  // maintainer can safely run this generator on an exported repository.
  const filenames = fs.existsSync(path.join(root, ".git"))
    ? localFiles
    : [...new Set([...localFiles, ...existingByName.keys()])];

  return filenames
    .map((fname) => {
      const localPath = path.join(scriptsDir, fname);
      const mtime = fs.existsSync(localPath)
        ? getGitMtime(
            path.posix.join("ea-scripts", fname),
            existingByName.get(fname),
          )
        : existingByName.get(fname);
      return { fname, mtime: Math.round(mtime) };
    })
    .sort((a, b) => a.fname.localeCompare(b.fname));
};

validateCatalog();

if (checkOnly) {
  log(
    `[script-store] Catalog OK: ${catalog.scripts.length} scripts in ${catalog.categories.length} categories.`,
  );
  process.exit(0);
}

fs.writeFileSync(legacyIndexPath, generateLegacyIndex());
fs.writeFileSync(
  directoryInfoPath,
  `${JSON.stringify(generateDirectoryInfo(), null, 2)}\n`,
);
log(
  `[script-store] Updated legacy index and directory-info.json from ${catalog.scripts.length} catalog entries.`,
);
